using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace Ursa.BindingsGenerator;

internal static partial class BindingEmitter
{
	private const string banner = "// <auto-generated> Ursa.BindingsGenerator. Edit the C# binding contract instead. </auto-generated>\n";
	private static string Cpp(WireType type) => type.Kind is "struct" or "optional" or "archive" ? "Wire::" + type.CppName : type.CppName;
	private static string TargetType(WireType type) => type.Key == "bool" ? "bool" : Cpp(type);
	private static string Cs(WireType type) => type.AbiName;
	private static string Check(WireType type) => "Check_" + ContractReader.Name(type.Key);
	private static string CheckOwned(WireType type) => "CheckOwned_" + ContractReader.Name(type.Key);
	private static string ConvertName(WireType type) => ContractReader.Name(type.Key);
	private static string Literal(string value) => JsonSerializer.Serialize(value);
	private static BindingMethod[] Functions(BindingModule module) => module.Methods.Where(m => m.Direction != BindingDirection.RecordedCommand).ToArray();

	internal static IReadOnlyDictionary<string, string> Emit(BindingModel model)
	{
		var files = new SortedDictionary<string, string>(StringComparer.Ordinal)
		{
			["Native/BindingTypes.generated.hpp"] = EmitNativeTypes(model),
			["Native/BindingManifest.generated.hpp"] = EmitNativeManifest(model),
			["Bindings.manifest.json"] = JsonSerializer.Serialize(new
			{
				Version = 1, Abi = "win-x64-cdecl-le", Generator = "Ursa.Bindings.v1",
				Modules = model.Modules.Select(m => new { m.Id, m.Name, m.Hash, m.CommandHash, m.Required, m.CallScoped, m.Dependencies, Methods = m.Methods.Select(f => new
					{ f.Identity, Direction = f.Direction.ToString(), Return = f.Return.Key,
						Parameters = f.Parameters.Select(p => new { p.Name, Type = p.Type.Key, p.HandleKind, p.Session }), f.Thread, f.NativeOnly }) })
			}, new JsonSerializerOptions { WriteIndented = true }) + "\n"
		};
		foreach (BindingModule module in model.Modules)
		{
			files[$"Native/{module.Name}.generated.hpp"] = EmitNativeModule(module);
			files[$"Managed/{module.Name}.g.cs"] = EmitManagedModule(module, model.Types);
			if (module.CommandHash.Length != 0)
			{
				files[$"Native/{module.Name}.Commands.generated.hpp"] = EmitNativeCommands(module);
				files[$"Managed/{module.Name}.Commands.g.cs"] = EmitManagedCommands(module);
			}
		}
		return files;
	}

	private static string EmitNativeManifest(BindingModel model)
	{
		var output = new StringBuilder(banner).Append("#pragma once\n#include <Core/Types.hpp>\n#include <array>\n\nnamespace Ursa::Scripting::Bindings::Manifest\n{\n");
		output.Append("inline constexpr const char* generator = \"Ursa.Bindings.v1\";\nstruct Module\n{\n\tUInt64 id;\n\tconst char* name;\n\tconst char* hash;\n\tUInt32 functionCount;\n\tbool required;\n\tbool callScoped;\n};\n");
		output.Append($"inline constexpr std::array<Module, {model.Modules.Count}> modules{{{{\n");
		foreach (BindingModule module in model.Modules)
			output.Append($"\t{{0x{module.Id:x16}ull, {Literal(module.Name)}, {Literal(module.Hash)}, {Functions(module).Length}, {module.Required.ToString().ToLowerInvariant()}, {module.CallScoped.ToString().ToLowerInvariant()}}},\n");
		return output.Append("}};\n} // namespace Ursa::Scripting::Bindings::Manifest\n").ToString();
	}

	private static IEnumerable<WireType> OrderedTypes(IReadOnlyList<WireType> source)
	{
		var seen = new HashSet<WireType>();
		var ordered = new List<WireType>();
		void Visit(WireType type)
		{
			if (!seen.Add(type)) return;
			if (type.Element != null) Visit(type.Element);
			foreach (WireField field in type.Fields) Visit(field.Type);
			ordered.Add(type);
		}
		foreach (WireType type in source) Visit(type);
		return ordered;
	}

	private static string EmitNativeTypes(BindingModel model)
	{
		var output = new StringBuilder(banner).Append("#pragma once\n#include <Scripting/Bindings/BindingRuntime.hpp>\n#include <cstddef>\n#include <type_traits>\n\nnamespace Ursa::Scripting::Bindings\n{\n");
		output.Append(BuiltinAbi.NativeAssertions()).Append("namespace Wire\n{\n");
		foreach (WireType type in model.Types.Where(t => t.Kind == "enum"))
		{
			output.Append($"struct {type.NativeEnumName}\n{{\n");
			foreach (WireEnumMember member in type.EnumValues)
				output.Append($"\tstatic constexpr {Cpp(type)} V_{member.Name} = static_cast<{Cpp(type)}>(0x{member.Bits:x16}ull);\n");
			output.Append("};\n");
		}
		foreach (WireType type in OrderedTypes(model.Types).Where(t => t.Kind is "struct" or "optional" or "archive"))
		{
			output.Append($"struct {type.CppName}\n{{\n");
			int offset = 0;
			if (type.IsClass || type.Kind == "optional") { output.Append("\tUInt32 present = 0;\n"); offset = 4; }
			var offsets = new List<(string, int)>();
			foreach (WireField field in type.Fields)
			{
				offset = ContractReader.Align(offset, field.Type.Alignment);
				string fieldCpp = field.Type.Kind is "struct" or "optional" or "archive" ? field.Type.CppName : field.Type.CppName;
				output.Append($"\t{fieldCpp} F_{field.Name}{{}};\n");
				offsets.Add((field.Name, offset));
				offset += field.Type.Size;
			}
			output.Append($"}};\nstatic_assert(sizeof({type.CppName}) == {type.Size}, \"Wire type size mismatch\");\n");
			foreach ((string name, int expected) in offsets)
				output.Append($"static_assert(offsetof({type.CppName}, F_{name}) == {expected}, \"Wire field offset mismatch\");\n");
		}
		output.Append("} // namespace Wire\n");
		foreach (WireType type in OrderedTypes(model.Types).Where(t => t.Key != "void"))
		{
			output.Append($"inline void {Check(type)}(const {Cpp(type)}& value)\n{{\n\t(void)value;\n");
			if (type.Key == "bool") output.Append("\tif (value > 1) throw std::runtime_error(\"Invalid binding boolean\");\n");
			if (type.Kind == "string")
			{
				output.Append($"\tValidateUtf8(value, {type.Nullable.ToString().ToLowerInvariant()});\n");
			}
			else if (type.Kind is "array" or "span")
			{
				output.Append($"\tValidate(value.data, value.length, sizeof({Cpp(type.Element!)}), value.present, value.reserved);\n");
				if (!type.Nullable) output.Append("\tif (!value.present) throw std::runtime_error(\"Required binding array is null\");\n");
				output.Append($"\tconst auto* items = static_cast<const {Cpp(type.Element!)}*>(value.data);\n\tfor (UInt64 index = 0; index < value.length; ++index) {Check(type.Element!)}(items[index]);\n");
			}
			else if (type.Fields.Count > 0)
			{
				if (type.IsClass || type.Kind == "optional")
				{
					output.Append("\tif (value.present > 1) throw std::runtime_error(\"Invalid wire presence marker\");\n");
					if (type.IsClass && !type.Nullable) output.Append("\tif (!value.present) throw std::runtime_error(\"Required wire DTO is null\");\n");
					output.Append("\tif (!value.present) return;\n");
				}
				foreach (WireField field in type.Fields) output.Append($"\t{Check(field.Type)}(value.F_{field.Name});\n");
			}
			output.Append("}\n");
			if (type.NeedsArena)
			{
				output.Append($"inline void {CheckOwned(type)}(const {Cpp(type)}& value, const BindingArena& arena)\n{{\n");
				if (type.Kind is "string" or "array" or "span")
				{
					string stride = type.Kind == "string" ? "1" : "sizeof(" + Cpp(type.Element!) + ")";
					output.Append($"\tValidate(value.data, value.length, {stride}, value.present, value.reserved);\n\tarena.RequireOwned(value.data, value.length, {stride});\n");
					if (type.Kind != "string" && type.Element!.NeedsArena)
						output.Append($"\tconst auto* items = static_cast<const {Cpp(type.Element!)}*>(value.data);\n\tfor (UInt64 index = 0; index < value.length; ++index) {CheckOwned(type.Element!)}(items[index], arena);\n");
				}
				else
				{
					if (type.IsClass || type.Kind == "optional")
						output.Append("\tif (value.present > 1) throw std::runtime_error(\"Invalid wire presence marker\");\n\tif (!value.present) return;\n");
					foreach (WireField field in type.Fields.Where(f => f.Type.NeedsArena))
						output.Append($"\t{CheckOwned(field.Type)}(value.F_{field.Name}, arena);\n");
				}
				output.Append("}\n");
			}
		}
		return output.Append("} // namespace Ursa::Scripting::Bindings\n").ToString();
	}

	private static string EmitNativeModule(BindingModule module)
	{
		var output = new StringBuilder(banner).Append("#pragma once\n#include \"BindingTypes.generated.hpp\"\n");
		foreach (string header in module.Headers) output.Append($"#include <{header}>\n");
		output.Append($"\nnamespace Ursa::Scripting::Bindings::{module.Name}\n{{\n");
		output.Append($"inline constexpr UInt64 moduleId = 0x{module.Id:x16}ull;\n");
		BindingMethod[] functions = Functions(module);
		output.Append("struct Table\n{\n");
		if (functions.Length == 0) output.Append("\tvoid* reserved = nullptr;\n");
		foreach (BindingMethod method in functions)
			output.Append($"\tInt32 (*{ContractReader.Slot(method)})(void*" +
				string.Concat(method.Parameters.Select(p => $", {(p.Type.Indirect ? "const " : "")}{Cpp(p.Type)}{(p.Type.Indirect ? "*" : "")}")) +
				(method.Return.Key != "void" ? $", {Cpp(method.Return)}*" : "") + ", BindingOutcome*) = nullptr;\n");
		output.Append("};\n");
		foreach (BindingMethod method in functions.Where(m => m.Direction == BindingDirection.NativeMethod))
		{
			string slot = ContractReader.Slot(method);
			output.Append($"// Contract: {method.Location.SourceTree?.FilePath}:{method.Location.GetLineSpan().StartLinePosition.Line + 1}\n");
			output.Append($"#line {method.Location.GetLineSpan().StartLinePosition.Line + 1} {Literal(method.Location.SourceTree!.FilePath)}\n");
			output.Append($"inline Int32 {slot}(void* context" + string.Concat(method.Parameters.Select(p =>
				$", {(p.Type.Indirect ? "const " : "")}{Cpp(p.Type)}{(p.Type.Indirect ? "*" : "")} p_{p.Name}")) +
				(method.Return.Key != "void" ? $", {Cpp(method.Return)}* result" : "") + ", BindingOutcome* outcome) noexcept\n{\n");
			output.Append($"\treturn Invoke(context, outcome, {method.Thread}, [&](BindingCall& call)\n\t{{\n");
			foreach (BindingParameter parameter in method.Parameters)
			{
				if (parameter.Type.Indirect) output.Append($"\t\tif (!p_{parameter.Name}) throw std::runtime_error(\"Null binding parameter: {parameter.Name}\");\n");
				string value = (parameter.Type.Indirect ? "*" : "") + "p_" + parameter.Name;
				output.Append($"\t\t{Check(parameter.Type)}({value});\n");
				if (parameter.HandleKind != 0)
					output.Append($"\t\tcall.context.CheckHandle(p_{parameter.Name}, sizeof(*p_{parameter.Name}), {parameter.HandleKind});\n");
			}
			if (method.Return.Key != "void") output.Append("\t\tif (!result) throw std::runtime_error(\"Null binding output\");\n");
			string signature = $"Result<{TargetType(method.Return)}> (*)(BindingCall&" +
				string.Concat(method.Parameters.Select(p => $", {(p.Type.Indirect ? "const " : "")}{TargetType(p.Type)}{(p.Type.Indirect ? "&" : "")}")) + ")";
			output.Append($"\t\tusing TargetSignature = {signature};\n\t\tstatic_assert(std::is_same_v<decltype(&::{method.Target}), TargetSignature>, \"Native binding target signature mismatch: {method.Identity}\");\n");
			string call = "::" + method.Target + "(call" + string.Concat(method.Parameters.Select(p =>
				", " + (p.Type.Key == "bool" ? "(p_" + p.Name + " != 0)" : (p.Type.Indirect ? "*" : "") + "p_" + p.Name))) + ")";
			if (method.Return.Key == "void") output.Append($"\t\tCompleteBindingResult({call});\n");
			else
			{
				output.Append($"\t\t*result = TakeBindingResult({call}){(method.Return.Key == "bool" ? " ? 1u : 0u" : "")};\n");
				if (method.Return.NeedsArena) output.Append($"\t\t{CheckOwned(method.Return)}(*result, call.arena);\n");
				output.Append($"\t\t{Check(method.Return)}(*result);\n");
			}
			output.Append("\t});\n}\n");
			output.Append($"#line 1 \"{module.Name}.generated.hpp\"\n");
		}
		output.Append("inline const BindingModuleDescriptor& NativeDescriptor()\n{\n\tstatic const Table table\n\t{\n");
		if (functions.Length == 0) output.Append("\t\tnullptr\n");
		foreach (BindingMethod method in functions)
			output.Append($"\t\t{(method.Direction == BindingDirection.NativeMethod ? "&" + ContractReader.Slot(method) : "nullptr")},\n");
		output.Append($"\t}};\n\tstatic const BindingModuleDescriptor descriptor{{1, sizeof(BindingModuleDescriptor), sizeof(void*), {functions.Length}, &table, &ValidateBindingContext, {{" +
			string.Join(", ", Enumerable.Range(0, 32).Select(i => "0x" + module.Hash.Substring(i * 2, 2))) + "}};\n\treturn descriptor;\n}\n");
		if (functions.Any(m => m.Direction == BindingDirection.ManagedCallback))
		{
			output.Append("inline Result<CallbackModule<Table>> ConnectCallbacks(const BindingModuleDescriptor* descriptor, void* context)\n{\n\tauto result = ConnectCallbackModule<Table>(descriptor, NativeDescriptor(), context);\n\tif (!result) return result;\n");
			foreach (BindingMethod method in functions.Where(m => m.Direction == BindingDirection.ManagedCallback))
				output.Append($"\tif (!result.value.table.{ContractReader.Slot(method)}) return Result<CallbackModule<Table>>::Failure(\"Missing callback: {method.Identity}\");\n");
			output.Append("\treturn result;\n}\n");
			foreach (BindingMethod method in functions.Where(m => m.Direction == BindingDirection.ManagedCallback))
			{
				output.Append($"inline CallbackResult<{Cpp(method.Return)}> Call_{ContractReader.Slot(method)}(const CallbackModule<Table>& module" +
					string.Concat(method.Parameters.Select(p => $", {(p.Type.Indirect ? "const " : "")}{Cpp(p.Type)}{(p.Type.Indirect ? "&" : "")} p_{p.Name}")) + ")\n{\n");
				output.Append($"\tCallbackResult<{Cpp(method.Return)}> result;\n\tresult.entry = {Literal(method.Identity)};\n\tresult.status = module.table.{ContractReader.Slot(method)}(module.context" +
					string.Concat(method.Parameters.Select(p => ", " + (p.Type.Indirect ? "&" : "") + "p_" + p.Name)) +
					(method.Return.Key != "void" ? ", &result.value" : "") + ", &result.outcome);\n\treturn result;\n}\n");
			}
		}
		return output.Append($"}} // namespace Ursa::Scripting::Bindings::{module.Name}\n").ToString();
	}

	private static string EmitManagedModule(BindingModule module, IReadOnlyList<WireType> types)
	{
		var used = new HashSet<WireType>();
		void Collect(WireType type)
		{
			if (!used.Add(type)) return;
			if (type.Element != null) Collect(type.Element);
			foreach (WireField field in type.Fields) Collect(field.Type);
		}
		foreach (BindingMethod method in module.Methods)
		{
			Collect(method.Return);
			foreach (BindingParameter parameter in method.Parameters) Collect(parameter.Type);
		}
		WireType[] moduleTypes = types.Where(used.Contains).ToArray();
		string owner = module.Name + "Module";
		var output = new StringBuilder(banner).Append("#nullable enable\nusing System;\nusing System.Runtime.CompilerServices;\nusing System.Runtime.InteropServices;\nusing Ursa.Bindings;\n\nnamespace Ursa.Bindings.Generated\n{\n");
		output.Append($"internal static unsafe class {owner}\n{{\n\tinternal const string Hash = \"{module.Hash}\";\n\t[ThreadStatic] private static nint functions;\n\t[ThreadStatic] internal static nint Context;\n\t[ThreadStatic] private static int ownerThread;\n");
		BindingMethod[] functions = Functions(module);
		output.Append($"\tinternal const ulong Id = 0x{module.Id:x16}ul;\n\t[ModuleInitializer]\n\tinternal static void Register() => BindingRegistry.Register(new BindingModuleRegistration(Id, {Literal(module.Name)}, Hash, {functions.Length}, {module.Required.ToString().ToLowerInvariant()}, {module.CallScoped.ToString().ToLowerInvariant()}, new ulong[] {{ " +
			string.Join(", ", module.Dependencies.Select(d => $"0x{BindingModule.IdFor(d):x16}ul")) +
			$" }}, Bind, Clear, {(functions.Any(m => m.Direction == BindingDirection.ManagedCallback) ? "CreateCallbacks" : "null")}));\n");
		output.Append("\t[StructLayout(LayoutKind.Sequential)]\n\tinternal struct Table\n\t{\n");
		if (functions.Length == 0) output.Append("\t\tinternal nint reserved;\n");
		foreach (BindingMethod method in functions)
			output.Append($"\t\tinternal delegate* unmanaged[Cdecl]<nint" + string.Concat(method.Parameters.Select(p =>
				$", {Cs(p.Type)}{(p.Type.Indirect ? "*" : "")}")) + (method.Return.Key != "void" ? $", {Cs(method.Return)}*" : "") +
				$", BindingOutcome*, int> {ContractReader.Slot(method)};\n");
		output.Append("\t}\n");
		output.Append($"\tinternal static void Bind(nint descriptor, nint context)\n\t{{\n\t\tBindingMemory.ValidateModule(descriptor, Hash, {functions.Length}, \"{module.Name}\");\n\t\tBindingMemory.ValidateContext(descriptor, context, \"{module.Name}\");\n\t\tfunctions = ((BindingModuleDescriptor*)descriptor)->Functions;\n\t\tContext = context;\n\t\townerThread = Environment.CurrentManagedThreadId;\n\t}}\n");
		output.Append("\tinternal static void Clear() { functions = 0; Context = 0; ownerThread = 0; }\n\tinternal static Table* Require(uint policy)\n\t{\n\t\tBindingRegistry.RequireCurrent();\n\t\tif (functions == 0 || (policy == 0 && ownerThread != Environment.CurrentManagedThreadId)) throw new InvalidOperationException(\"Binding module is unavailable on this thread.\");\n\t\treturn (Table*)functions;\n\t}\n");
		foreach (WireType type in OrderedTypes(moduleTypes).Where(t => t.Kind is "struct" or "optional" or "archive"))
		{
			output.Append($"\t[StructLayout(LayoutKind.Sequential)]\n\tinternal struct {type.AbiName}\n\t{{\n");
			if (type.IsClass || type.Kind == "optional") output.Append("\t\tinternal uint Present;\n");
			foreach (WireField field in type.Fields) output.Append($"\t\tinternal {Cs(field.Type)} F_{field.Name};\n");
			output.Append("\t}\n");
		}
		foreach (WireType type in moduleTypes.Where(t => t.Key != "void")) EmitManagedConversion(output, type);
		output.Append($"\tinternal static BindingCallbackRegistration CreateCallbacks(ulong sessionIdentity = 0)\n\t{{\n\t\tvar registration = new BindingCallbackRegistration(Hash, {functions.Length}, sizeof(Table), sessionIdentity);\n\t\tvar table = (Table*)registration.Functions;\n");
		foreach (BindingMethod method in functions.Where(m => m.Direction == BindingDirection.ManagedCallback))
			output.Append($"\t\ttable->{ContractReader.Slot(method)} = &Callback_{ContractReader.Slot(method)};\n");
		output.Append("\t\treturn registration;\n\t}\n");
		foreach (BindingMethod method in functions.Where(m => m.Direction == BindingDirection.ManagedCallback)) EmitCallback(output, method);
		output.Append("}\n}\n");
		foreach (var group in module.Methods.Where(m => m.Direction != BindingDirection.RecordedCommand).GroupBy(m => (m.CsNamespace, m.CsClass)))
		{
			if (group.Key.CsNamespace.Length != 0) output.Append($"namespace {group.Key.CsNamespace}\n{{\n");
			output.Append($"internal static unsafe partial class {group.Key.CsClass}\n{{\n");
			foreach (BindingMethod method in group)
			{
				output.Append($"\tinternal static partial {method.Return.CsName} {method.Name}(" + string.Join(", ", method.Parameters.Select(p => $"{p.Type.CsName} @{p.Name}")) + ")\n\t{\n");
				if (method.Direction == BindingDirection.ManagedCallback)
				{
					output.Append("\t\t" + (method.Return.Key != "void" ? "return " : "") + "global::" + method.Target + "(" + string.Join(", ", method.Parameters.Select(p => "@" + p.Name)) + ");\n");
				}
				else
				{
					string moduleCs = "global::Ursa.Bindings.Generated." + owner;
					output.Append($"\t\tvar table = {moduleCs}.Require({method.Thread});\n\t\tif (table->{ContractReader.Slot(method)} == null) throw new InvalidOperationException(\"Missing native entry: {method.Identity}\");\n");
					bool arena = method.Parameters.Any(p => p.Type.NeedsArena);
					if (arena) output.Append("\t\tusing var arena = new BindingArena();\n");
					foreach (BindingParameter parameter in method.Parameters)
						output.Append($"\t\tvar p_{parameter.Name} = {moduleCs}.To_{ConvertName(parameter.Type)}(@{parameter.Name}, {(arena ? "arena" : "null")});\n");
					output.Append("\t\tBindingOutcome outcome = default;\n\t\ttry\n\t\t{\n");
					if (method.Return.Key != "void") output.Append($"\t\t\t{QualifyCs(method.Return, moduleCs)} result = default;\n");
					output.Append($"\t\t\tint status = table->{ContractReader.Slot(method)}({moduleCs}.Context" + string.Concat(method.Parameters.Select(p =>
						", " + (p.Type.Indirect ? "&" : "") + "p_" + p.Name)) + (method.Return.Key != "void" ? ", &result" : "") + ", &outcome);\n");
					output.Append($"\t\t\tBindingMemory.ThrowIfFailed(status, outcome, {Literal(method.Identity)});\n");
					if (method.Return.Key != "void") output.Append($"\t\t\treturn {moduleCs}.From_{ConvertName(method.Return)}(result);\n");
					output.Append("\t\t}\n\t\tfinally { BindingMemory.Release(ref outcome); }\n");
				}
				output.Append("\t}\n");
			}
			output.Append("}\n");
			if (group.Key.CsNamespace.Length != 0) output.Append("}\n");
		}
		return output.ToString();
	}

	private static string QualifyCs(WireType type, string owner) => type.Kind is "struct" or "optional" or "archive" ? owner + "." + Cs(type) : Cs(type);
	private static string To(WireType type, string value, string arena = "arena") => $"To_{ConvertName(type)}({value}, {arena})";
	private static string From(WireType type, string value) => $"From_{ConvertName(type)}({value})";

	private static void EmitManagedConversion(StringBuilder output, WireType type)
	{
		output.Append($"\tinternal static {Cs(type)} To_{ConvertName(type)}({type.CsName} value, BindingArena? arena)\n\t{{\n");
		if (type.Kind is "scalar" or "enum")
			output.Append("\t\treturn " + (type.Key == "bool" ? "value ? 1u : 0u" : type.Kind == "enum" ? "(" + Cs(type) + ")value" : "value") + ";\n");
		else if (type.Kind == "string") output.Append($"\t\treturn arena!.String(value, {type.Nullable.ToString().ToLowerInvariant()});\n");
		else if (type.Kind is "array" or "span")
		{
			WireType element = type.Element!;
			output.Append($"\t\treturn arena!.{(type.Kind == "span" ? "Span" : "Array")}<{element.CsName}, {Cs(element)}>(value, static (item, owner) => {To(element, "item", "owner")}" +
				(type.Kind == "array" ? ", " + type.Nullable.ToString().ToLowerInvariant() : "") + ");\n");
		}
		else
		{
			if (type.Kind == "optional") output.Append("\t\tif (!value.HasValue) return default;\n");
			else if (type.IsClass)
				output.Append(type.Nullable ? "\t\tif (value == null) return default;\n" : "\t\tArgumentNullException.ThrowIfNull(value);\n");
			output.Append($"\t\treturn new {Cs(type)}\n\t\t{{\n");
			if (type.IsClass || type.Kind == "optional") output.Append("\t\t\tPresent = 1,\n");
			foreach (WireField field in type.Fields)
				output.Append($"\t\t\tF_{field.Name} = {To(field.Type, type.Kind == "optional" ? "value.Value" : "value.@" + field.Name)},\n");
			output.Append("\t\t};\n");
		}
		output.Append("\t}\n");
		if (type.Kind == "span") return;
		output.Append($"\tinternal static {type.CsName} From_{ConvertName(type)}({Cs(type)} value)\n\t{{\n");
		if (type.Kind is "scalar" or "enum")
			output.Append("\t\treturn " + (type.Key == "bool" ? "BindingMemory.Bool(value)" : type.Kind == "enum" ? "(" + type.CsName + ")value" : "value") + ";\n");
		else if (type.Kind == "string") output.Append($"\t\treturn BindingMemory.String(value, {type.Nullable.ToString().ToLowerInvariant()}){(type.Nullable ? "" : "!")};\n");
		else if (type.Kind == "array")
			output.Append($"\t\treturn BindingMemory.Array<{Cs(type.Element!)}, {type.Element!.CsName}>(value, static item => {From(type.Element!, "item")}, {type.Nullable.ToString().ToLowerInvariant()}){(type.Nullable ? "" : "!")};\n");
		else
		{
			if (type.IsClass || type.Kind == "optional")
			{
				output.Append("\t\tif (value.Present > 1) throw new InvalidOperationException(\"Invalid wire presence marker.\");\n");
				output.Append(type.Nullable || type.Kind == "optional" ? "\t\tif (value.Present == 0) return null;\n" : "\t\tif (value.Present == 0) throw new InvalidOperationException(\"Required wire DTO is null.\");\n");
			}
			if (type.Kind == "optional") output.Append($"\t\treturn {From(type.Element!, "value.F_value")};\n");
			else
			{
				output.Append($"\t\treturn new {type.CsName.TrimEnd('?')}\n\t\t{{\n");
				foreach (WireField field in type.Fields) output.Append($"\t\t\t@{field.Name} = {From(field.Type, "value.F_" + field.Name)},\n");
				output.Append("\t\t};\n");
			}
		}
		output.Append("\t}\n");
	}

	private static void EmitCallback(StringBuilder output, BindingMethod method)
	{
		string session = method.Parameters.FirstOrDefault(p => p.Session) is { } sessionParameter ? "p_" + sessionParameter.Name : "0";
		output.Append("\t[UnmanagedCallersOnly(CallConvs = new[] { typeof(CallConvCdecl) })]\n");
		output.Append($"\tprivate static int Callback_{ContractReader.Slot(method)}(nint context" + string.Concat(method.Parameters.Select(p =>
			$", {Cs(p.Type)}{(p.Type.Indirect ? "*" : "")} p_{p.Name}")) +
			(method.Return.Key != "void" ? $", {Cs(method.Return)}* result" : "") + ", BindingOutcome* outcome)\n\t{\n\t\tBindingArena? arena = null;\n\t\ttry\n\t\t{\n");
		output.Append($"\t\t\tif (outcome == null) return 1;\n\t\t\t*outcome = default;\n\t\t\tBindingCallbackRegistration.Require(context, {method.Thread});\n\t\t\toutcome->SessionIdentity = {(session == "0" ? "BindingCallbackRegistration.SessionIdentity(context)" : session)};\n");
		foreach (BindingParameter parameter in method.Parameters.Where(p => p.Type.Indirect))
			output.Append($"\t\t\tif (p_{parameter.Name} == null) throw new ArgumentException(\"Null callback parameter: {parameter.Name}\");\n");
		if (method.Return.Key != "void") output.Append("\t\t\tif (result == null) throw new ArgumentException(\"Null callback result\");\n");
		output.Append($"\t\t\tdelegate* managed<" + string.Join(", ", method.Parameters.Select(p => p.Type.CsName).Append(method.Return.CsName)) + $"> target = &global::{method.Target};\n");
		string call = "target(" + string.Join(", ", method.Parameters.Select(p =>
			p.Type.Kind == "span" ? $"BindingMemory.Array<{Cs(p.Type.Element!)}, {p.Type.Element!.CsName}>(*p_{p.Name}, static item => {From(p.Type.Element!, "item")}, false)!" :
			From(p.Type, (p.Type.Indirect ? "*" : "") + "p_" + p.Name))) + ")";
		output.Append("\t\t\t" + (method.Return.Key != "void" ? "var value = " : "") + call + ";\n");
		if (method.Return.Key != "void")
		{
			if (method.Return.NeedsArena) output.Append("\t\t\tarena = new BindingArena();\n");
			output.Append($"\t\t\t*result = {To(method.Return, "value")};\n");
		}
		output.Append($"\t\t\tif (arena != null) {{ arena.Transfer(ref *outcome); arena = null; }}\n\t\t\treturn 0;\n\t\t}}\n\t\tcatch (Exception error) {{ return BindingMemory.Fail(error, outcome, {Literal(method.Identity)}, context, {session}); }}\n\t\tfinally {{ arena?.Dispose(); }}\n\t}}\n");
	}
